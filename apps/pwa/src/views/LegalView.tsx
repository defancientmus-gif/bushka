import { useEffect, useState } from 'react';
import { useStore } from '../lib/store';
import { removeListing } from '../lib/cloud';
import { ChevronIcon } from '../components/icons';
import {
  LEGAL_HASH,
  OPERATOR,
  POLICY_DATE_LABEL,
  REQUISITES,
  clearPdConsent,
  formatConsentDate,
  loadCookieChoice,
  loadPdConsent,
  resetCookieChoice,
  type PdConsent
} from '../lib/legal';

// Политика обработки персональных данных (152-ФЗ, ст. 18.1 — опубликована в открытом доступе)
// + тексты обоих согласий (ст. 9 и ст. 10.1 — каждое отдельным документом) + cookie.
// Тон — человеческий: кто первый раз продаёт вещь, должен понять, что происходит с его данными.

const SITE = 'https://defancientmus-gif.github.io/bushka/';

export function LegalView({ anchor, onBack }: { anchor: string; onBack: () => void }) {
  const { items, showToast } = useStore();
  const [consent, setConsent] = useState<PdConsent | null>(() => loadPdConsent());
  const [cookie, setCookie] = useState(() => loadCookieChoice());
  const [withdrawing, setWithdrawing] = useState(false);

  // Открыли по ссылке на раздел (#privacy-consent и т.п.) — встаём на него.
  useEffect(() => {
    const id = anchor.replace('#', '');
    const target = id && id !== 'privacy' ? document.getElementById(id) : null;
    window.setTimeout(() => (target ? target.scrollIntoView({ block: 'start' }) : window.scrollTo({ top: 0 })), 0);
  }, [anchor]);

  useEffect(() => {
    const sync = () => setCookie(loadCookieChoice());
    window.addEventListener('bushka:cookies', sync);
    return () => window.removeEventListener('bushka:cookies', sync);
  }, []);

  async function withdraw() {
    if (!withdrawing) {
      setWithdrawing(true);
      return;
    }
    clearPdConsent();
    setConsent(null);
    setWithdrawing(false);
    // Отзыв = прекращаем распространение: снимаем свои объявления с общей витрины. Склад на телефоне остаётся.
    await Promise.all(items.map(item => removeListing(item.id)));
    showToast('Согласие отозвано · объявления сняты с витрины');
  }

  return (
    <section className="view legal-view">
      <button type="button" className="legal-back" onClick={onBack}>
        <ChevronIcon size={18} />Назад
      </button>

      <header className="view-head">
        <p className="eyebrow">документы</p>
        <h1>Ваши данные</h1>
      </header>

      <div className="legal-tldr">
        <strong>Коротко, по-человечески</strong>
        <ul>
          <li>Покупателю регистрироваться не нужно — о нём мы ничего не собираем.</li>
          <li>Продавец сам решает, что показать в объявлении: имя, город, контакт.</li>
          <li>Закупочная цена и откуда товар — остаются только у вас в телефоне.</li>
          <li>Рекламных и следящих cookie нет.</li>
          <li>Передумали — отзовите согласие одной кнопкой ниже, объявления снимутся с витрины.</li>
        </ul>
      </div>

      <nav className="legal-toc" aria-label="Разделы">
        <a href={LEGAL_HASH.policy}>Политика</a>
        <a href={LEGAL_HASH.consent}>Согласие на обработку</a>
        <a href={LEGAL_HASH.publish}>Согласие на показ в объявлении</a>
        <a href={LEGAL_HASH.cookies}>Cookie</a>
      </nav>

      <article className="legal-doc" id="privacy-policy">
        <h2>Политика обработки персональных данных</h2>
        <p className="legal-meta">Редакция от {POLICY_DATE_LABEL} · сайт и приложение «БУ.шка» ({SITE})</p>

        <h3>1. Кто обрабатывает данные</h3>
        <p>Оператор персональных данных — {OPERATOR}, ИНН {REQUISITES.inn}, ОГРНИП {REQUISITES.ogrnip}, г. {REQUISITES.city} (далее — «мы»). Политика составлена по Федеральному закону от 27.07.2006 № 152-ФЗ «О персональных данных» и действует для всех данных, которые мы получаем через сайт и приложение «БУ.шка».</p>

        <h3>2. Какие данные и чьи</h3>
        <p><b>Продавцы</b>, которые выставляют товар в общую витрину: имя или название магазина, город, контакт для связи (номер телефона или имя пользователя в Telegram), а также то, что продавец сам положил в объявление, — фото, видео, описание. Для работы витрины устройству выдаётся обезличенный технический идентификатор (анонимный вход без логина и пароля).</p>
        <p><b>Покупатели</b>: ничего. Смотреть витрину и связываться с продавцом можно без регистрации. Избранное хранится только в вашем браузере.</p>
        <p><b>Оценщик телефона</b>: фото и параметры телефона обрабатываются прямо в браузере и никуда не отправляются.</p>
        <p><b>Технические данные</b>: как любой сайт, хостинг GitHub Pages (GitHub, Inc.) при открытии страниц получает IP-адрес и сведения о браузере. Мы эти данные не собираем и не анализируем.</p>
        <p>Мы <b>не собираем</b> паспортные данные, адреса, платёжные данные, биометрию и специальные категории данных. Закупочная цена и источник товара в облако не уходят никогда.</p>

        <h3>3. Зачем</h3>
        <ul>
          <li>показать объявление продавца в общей витрине;</li>
          <li>дать покупателю связаться с продавцом;</li>
          <li>обеспечить работу приложения (склад, настройки, перенос объявления по ссылке на публичный пост Telegram).</li>
        </ul>
        <p>Рассылок, рекламы и передачи данных для маркетинга нет.</p>

        <h3>4. На каком основании</h3>
        <p>Согласие на обработку (п. 1 ч. 1 ст. 6 152-ФЗ) и отдельное согласие на распространение — показ данных в объявлении неограниченному кругу лиц (ст. 10.1 152-ФЗ). Оба согласия даются галочками перед первой публикацией, их тексты — ниже.</p>

        <h3>5. Что мы с данными делаем</h3>
        <p>Сбор, запись, систематизация, накопление, хранение, уточнение (обновление, изменение), извлечение, использование, распространение (показ в объявлении), удаление и уничтожение. Обработка автоматизированная.</p>

        <h3>6. Где хранятся</h3>
        <p>Склад, профиль и настройки — в памяти вашего браузера (localStorage, IndexedDB) на вашем устройстве. Опубликованные объявления — в облачной базе данных витрины (сервис Supabase). Доступ к записи защищён: изменить или удалить объявление может только устройство, которое его выставило.</p>
        <p>Перенос объявления по ссылке на публичный пост Telegram: мы запрашиваем у Telegram этот публичный пост, чтобы перенести текст и фото в форму.</p>

        <h3>7. Сколько храним</h3>
        <p>Объявление — пока вы его не удалите или не отзовёте согласие; после этого оно снимается с витрины сразу, а из резервных копий удаляется в срок не более 30 дней. Данные в вашем браузере живут, пока вы их не удалите (очистка браузера или удаление товара).</p>

        <h3>8. Ваши права</h3>
        <p>Вы можете узнать, какие ваши данные мы обрабатываем, потребовать их уточнить, заблокировать или удалить, отозвать согласие, а также обжаловать наши действия в Роскомнадзоре или в суде. Запрос — на {REQUISITES.email}; отвечаем в течение 10 рабочих дней (срок может быть продлён не более чем на 5 рабочих дней с объяснением причины).</p>

        <h3>9. Как защищаем</h3>
        <p>Передача только по защищённому соединению (HTTPS); в облако уходят только поля, которые видит покупатель; права на запись в базе ограничены владельцем объявления; секретные ключи не хранятся в приложении.</p>

        <h3>10. Изменения</h3>
        <p>Новая редакция начинает действовать с момента публикации на этой странице. Дата редакции — вверху.</p>

        <h3>11. Связаться с оператором</h3>
        <p>{OPERATOR} · ИНН {REQUISITES.inn} · ОГРНИП {REQUISITES.ogrnip} · {REQUISITES.email}</p>
      </article>

      <article className="legal-doc" id="privacy-consent">
        <h2>Согласие на обработку персональных данных</h2>
        <p>Отмечая галочку «Согласен на обработку персональных данных», я свободно, своей волей и в своём интересе даю {OPERATOR} (ИНН {REQUISITES.inn}, ОГРНИП {REQUISITES.ogrnip}) согласие на обработку моих персональных данных: имя или название магазина, город, контакт для связи (телефон или имя пользователя Telegram), фото и описание товара в объявлении.</p>
        <p><b>Цель</b> — размещение моих объявлений в витрине «БУ.шка» и связь покупателей со мной. <b>Действия</b> — перечислены в разделе 5 Политики, обработка автоматизированная. <b>Срок</b> — до отзыва согласия.</p>
        <p>Я знаю, что могу отозвать согласие в любой момент — кнопкой на этой странице или письмом на {REQUISITES.email}.</p>
      </article>

      <article className="legal-doc" id="privacy-publish">
        <h2>Согласие на распространение персональных данных</h2>
        <p>Отмечая галочку «Согласен показывать мои данные в объявлении», я даю {OPERATOR} (ИНН {REQUISITES.inn}, ОГРНИП {REQUISITES.ogrnip}) согласие на распространение — показ неограниченному кругу лиц в витрине «БУ.шка» ({SITE}) — следующих данных: имя или название магазина, город, контакт для связи, фото и описание товара.</p>
        <p><b>Цель</b> — чтобы покупатели увидели объявление и связались со мной. <b>Условия</b>: данные показываются только в составе моих объявлений; передавать их третьим лицам для других целей оператору запрещено. Дополнительные запреты и условия я могу установить, написав на {REQUISITES.email}. <b>Срок</b> — до отзыва согласия или удаления объявления.</p>
      </article>

      <article className="legal-doc" id="privacy-cookies">
        <h2>Cookie и хранилище браузера</h2>
        <p>Рекламных, следящих и аналитических cookie у нас нет. Браузер хранит только то, без чего приложение не работает: ваш склад, избранное, тему оформления, технический вход для витрины и ваш выбор по cookie. Эти данные лежат на вашем устройстве и нам не передаются.</p>
        <p>Если когда-нибудь появится аналитика, она включится только у тех, кто нажал «Разрешить». «Только нужные» — такой же полноценный выбор: всё работает так же.</p>
        <p className="legal-state">Ваш выбор сейчас: <b>{cookie === 'all' ? 'разрешены все' : cookie === 'necessary' ? 'только нужные' : 'не сделан'}</b></p>
        <button type="button" className="ghost-btn" onClick={() => { resetCookieChoice(); showToast('Выберите заново внизу экрана'); }}>Изменить выбор cookie</button>
      </article>

      <article className="legal-doc legal-mine">
        <h2>Моё согласие</h2>
        {consent ? (
          <>
            <p>Вы дали согласие {formatConsentDate(consent.at)}. Пока оно действует, ваши объявления видны в общей витрине.</p>
            <button type="button" className={`ghost-btn wide ${withdrawing ? 'danger-soft' : ''}`} onClick={withdraw}>
              {withdrawing ? 'Точно отозвать? Объявления снимутся с витрины' : 'Отозвать согласие'}
            </button>
            <small className="legal-note">Склад на вашем телефоне останется — снимется только показ в витрине.</small>
          </>
        ) : (
          <p>Согласие не дано. Склад работает как обычно, а в общую витрину объявления попадут, когда вы отметите галочки при сохранении товара.</p>
        )}
      </article>
    </section>
  );
}
