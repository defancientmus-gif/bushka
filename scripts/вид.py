#!/usr/bin/env python3
"""Щит вида БУ.шки — проверяет свод texts/ПРАВИЛА-ВИДА.md машиной.

Зачем: правило, которое никто не проверяет, живёт один заход. Этот щит стоит в
pre-commit, падает с объяснением и не даёт вернуть то, на что Женя уже жаловался.

Запуск руками:  python3 scripts/вид.py
Осознанное исключение: комментарий «вид-ок: почему» на той же строке.
"""
import re
import subprocess
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parent.parent
CSS = КОРЕНЬ / 'apps/pwa/src/styles.css'
ИСХОДНИКИ = sorted((КОРЕНЬ / 'apps/pwa/src').rglob('*.tsx'))

беды: list[tuple[str, str, str]] = []  # правило, где, что


def добавить(правило: str, путь: Path, номер: int, строка: str) -> None:
    if 'вид-ок' in строка or 'почерк-ок' in строка:
        return
    где = f'{путь.relative_to(КОРЕНЬ)}:{номер}'
    беды.append((правило, где, строка.strip()[:110]))


def читать(путь: Path):
    return list(enumerate(путь.read_text(encoding='utf-8').splitlines(), 1))


# ——— 1. Нейтраль: цвет только у брони ——————————————————————————————
# Женя 18.11 14:09: «УБираем зеленый бежевый, нейтральные цвета».
# В oklch цветность (вторая цифра) больше нуля разрешена только янтарю брони
# (hue 55–75) и красному удаления (hue 20–30).
ЦВЕТ = re.compile(r'oklch\(\s*[\d.]+\s+(0?\.\d+)\s+(\d+(?:\.\d+)?)')
for номер, строка in читать(CSS):
    for цветность, тон in ЦВЕТ.findall(строка):
        if float(цветность) < 0.02:
            continue
        тон = float(тон)
        if 50 <= тон <= 80 or 15 <= тон <= 35:
            continue
        добавить('цвет вне брони и беды', CSS, номер, строка)

# ——— 2. Шкала SF: толщины 400/500/600/700, без заглавных с разрядкой ————
# Женя 18.11 15:26–15:27: «Нам нужен стиль apple )» · «Взять шрифты».
for номер, строка in читать(CSS):
    for вес in re.findall(r'font-weight:\s*(\d{3})', строка):
        if вес not in {'400', '500', '600', '700'}:
            добавить('толщина не из шкалы SF', CSS, номер, строка)
    if 'text-transform: uppercase' in строка:
        добавить('заглавные буквы', CSS, номер, строка)
    for трек in re.findall(r'letter-spacing:\s*(0\.\d+)(?:em|px)', строка):
        добавить('разрядка вместо плотного набора', CSS, номер, строка)

# ——— 3. Отступы по шагу 4 ———————————————————————————————————————
ОТСТУП = re.compile(r'\b(?:padding|margin|gap|row-gap|column-gap)[a-z-]*\s*:\s*([^;{}]+);')
for номер, строка in читать(CSS):
    for значения in ОТСТУП.findall(строка):
        for v in re.findall(r'(\d+(?:\.\d+)?)px', значения):
            ч = float(v)
            if ч > 1 and ч % 2:
                добавить('отступ мимо шага 4', CSS, номер, строка)

# ——— 4. Скругление не мельче 12 ————————————————————————————————————
for номер, строка in читать(CSS):
    for v in re.findall(r'border-radius:\s*([^;{}]+);', строка):
        for ч in re.findall(r'(\d+(?:\.\d+)?)px', v):
            if 0 < float(ч) < 12:
                добавить('скругление мельче 12', CSS, номер, строка)

# ——— 5. Обычное состояние не объявляем цветом ——————————————————————
# Женя 18.11: зелёная плашка «В наличии» на каждой карточке — первое, на что пожаловался.
for путь in ИСХОДНИКИ:
    строки = читать(путь)
    тексты = [т for _, т in строки]
    for номер, строка in строки:
        if 'status-pill' in строка and 'statusLabels' in строка:
            # отсев может стоять на обёртке выше — смотрим три строки вокруг
            окно = ' '.join(тексты[max(0, номер - 4):номер])
            if "!== 'available'" not in окно:
                добавить('плашка статуса без отсева «в наличии»', путь, номер, строка)

# ——— 6. Эмодзи в интерфейсе ————————————————————————————————————————
# Цветные эмодзи. ★ и другие типографские знаки эмодзи не считаются.
ЭМОДЗИ = re.compile('[\U0001F300-\U0001FAFF\u2614\u2615\u26A1\u2705\u2728\u274C\u2757\u2795-\u2797]')
for путь in [CSS, *ИСХОДНИКИ]:
    for номер, строка in читать(путь):
        if ЭМОДЗИ.search(строка) and not строка.lstrip().startswith(('//', '*', '/*')):
            добавить('эмодзи в интерфейсе', путь, номер, строка)

# ——— 7. Версия сборки поднята вместе с правкой фронта ————————————————
try:
    изменено = subprocess.run(
        ['git', 'diff', '--cached', '--name-only'],
        cwd=КОРЕНЬ, capture_output=True, text=True, timeout=10
    ).stdout.split()
except Exception:
    изменено = []
фронт = [f for f in изменено if f.startswith('apps/pwa/src/') or f.startswith('apps/pwa/public/')]
if фронт and 'apps/pwa/src/lib/version.ts' not in изменено:
    беды.append(('APP_BUILD не поднят', 'apps/pwa/src/lib/version.ts',
                 'правка фронта есть, версия та же — Женя увидит вчерашнее из кеша'))

# ——— Итог ——————————————————————————————————————————————————————————
if беды:
    print('✗ вид БУ.шки — коммит остановлен')
    по_правилам: dict[str, list] = {}
    for правило, где, что in беды:
        по_правилам.setdefault(правило, []).append((где, что))
    for правило, места in по_правилам.items():
        print(f'  [{правило}] {len(места)}')
        for где, что in места[:4]:
            print(f'      {где}  {что}')
        if len(места) > 4:
            print(f'      … ещё {len(места) - 4}')
    print('Свод: texts/ПРАВИЛА-ВИДА.md. Осознанно иначе — «вид-ок: почему» на той же строке.')
    sys.exit(1)

print('✓ вид БУ.шки — чисто')
